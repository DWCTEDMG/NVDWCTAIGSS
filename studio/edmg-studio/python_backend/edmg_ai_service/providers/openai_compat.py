from __future__ import annotations

import json
import re
from typing import Optional

import requests

from .base import PlanProvider
from ..schemas import PlanRequest, PlanResponse, PlanVariant


_JSON_RE = re.compile(r"\{.*\}", re.DOTALL)


def _string_value(value: object) -> str | None:
    if value is None:
        return None
    if isinstance(value, str):
        return value
    if isinstance(value, list):
        return "; ".join(str(item).strip() for item in value if str(item).strip())
    if isinstance(value, dict):
        return json.dumps(value, ensure_ascii=False)
    return str(value)


def _string_list(value: object) -> list[str]:
    if isinstance(value, list):
        return [str(item).strip() for item in value if str(item).strip()]
    if isinstance(value, str) and value.strip():
        return [value.strip()]
    return []


def _coerce_variant(value: object) -> object:
    if not isinstance(value, dict):
        return value
    coerced = dict(value)
    coerced["name"] = _string_value(coerced.get("name")) or "NVIDIA Scene Plan"
    coerced["logline"] = _string_value(coerced.get("logline")) or "Generated by the configured OpenAI-compatible planner."
    coerced["mood"] = _string_value(coerced.get("mood")) or ""
    coerced["visual_motifs"] = _string_list(coerced.get("visual_motifs"))
    coerced["color_palette"] = _string_list(coerced.get("color_palette"))

    scenes = coerced.get("scenes")
    if isinstance(scenes, list):
        normalized_scenes = []
        for scene in scenes:
            if not isinstance(scene, dict):
                continue
            normalized_scene = dict(scene)
            for field in ("prompt", "negative_prompt", "camera", "motion", "notes"):
                normalized_scene[field] = _string_value(normalized_scene.get(field))
            normalized_scenes.append(normalized_scene)
        coerced["scenes"] = normalized_scenes
    return coerced


def _extract_json(text: str) -> Optional[dict]:
    try:
        return json.loads(text)
    except Exception:
        pass
    m = _JSON_RE.search(text)
    if not m:
        return None
    try:
        return json.loads(m.group(0))
    except Exception:
        return None


class OpenAICompatPlanner(PlanProvider):
    """Calls any OpenAI-compatible `POST /v1/chat/completions` endpoint via `requests`."""

    def __init__(self, base_url: str, api_key: str | None, model: str, timeout_s: float = 180.0):
        b = base_url.rstrip("/")
        # Accept both forms:
        #  - http://host:port
        #  - http://host:port/v1
        if b.endswith("/v1"):
            b = b[:-3]
        self._base_url = b
        self._api_key = api_key
        self._model = model
        self._timeout_s = timeout_s

    @property
    def name(self) -> str:
        return "openai_compat"

    @property
    def model(self) -> Optional[str]:
        return self._model

    def plan(self, req: PlanRequest) -> PlanResponse:
        system = (
            "You are EDMG Director. Return STRICT JSON only. "
            "Do not echo the input. Generate a production music-video scene plan. "
            "The root object must be {\"variants\": [...]}. "
            "Each variant must have name, logline, mood, visual_motifs, color_palette, and scenes. "
            "Each scene must have start_s, end_s, prompt, negative_prompt, camera, motion, and notes. "
            "color_palette and visual_motifs must be arrays of plain strings, never objects."
        )

        ctx = {
            "title": req.title,
            "duration_s": req.duration_s,
            "bpm": req.bpm,
            "tags": req.tags,
            "user_notes": req.user_notes,
            "style_prefs": req.style_prefs,
            "lyrics": (req.lyrics[:2000] if req.lyrics else None),
            "num_variants": req.num_variants,
            "max_scenes": req.max_scenes,
        }

        headers = {"Content-Type": "application/json"}
        if self._api_key:
            headers["Authorization"] = f"Bearer {self._api_key}"

        payload = {
            "model": self._model,
            "messages": [
                {"role": "system", "content": system},
                {
                    "role": "user",
                    "content": (
                        "Create exactly "
                        + str(max(1, int(req.num_variants or 1)))
                        + " variant(s), each with no more than "
                        + str(max(1, int(req.max_scenes or 1)))
                        + " scene(s). Input JSON:\n"
                        + json.dumps(ctx, ensure_ascii=False)
                    ),
                },
            ],
            "temperature": 0.25,
            "max_tokens": max(700, min(2800, int(req.max_scenes or 6) * 260 + 320)),
            "response_format": {"type": "json_object"},
        }

        try:
            r = requests.post(
                f"{self._base_url}/v1/chat/completions",
                headers=headers,
                json=payload,
                timeout=self._timeout_s,
            )
            if getattr(r, "status_code", 200) in (400, 422) and payload.get("response_format"):
                retry_payload = dict(payload)
                retry_payload.pop("response_format", None)
                r = requests.post(
                    f"{self._base_url}/v1/chat/completions",
                    headers=headers,
                    json=retry_payload,
                    timeout=self._timeout_s,
                )
            r.raise_for_status()
            data = r.json()
            text = data["choices"][0]["message"]["content"]
        except Exception as exc:
            raise RuntimeError(f"NVIDIA/OpenAI-compatible planner request failed: {exc}") from exc

        obj = _extract_json(text)
        if obj and "variants" not in obj and isinstance(obj.get("scenes"), list):
            obj = {
                "variants": [
                    {
                        "name": obj.get("name") or obj.get("title") or "NVIDIA Scene Plan",
                        "logline": obj.get("logline") or "Generated by the configured OpenAI-compatible planner.",
                        "mood": obj.get("mood") or "",
                        "visual_motifs": obj.get("visual_motifs") if isinstance(obj.get("visual_motifs"), list) else [],
                        "color_palette": obj.get("color_palette") if isinstance(obj.get("color_palette"), list) else [],
                        "scenes": obj.get("scenes"),
                    }
                ]
            }
        if not obj or "variants" not in obj:
            raise RuntimeError("NVIDIA/OpenAI-compatible planner returned a response without variants.")

        try:
            variants = [PlanVariant.model_validate(_coerce_variant(v)) for v in obj["variants"]]
            return PlanResponse(provider=self.name, model=self._model, variants=variants)
        except Exception as exc:
            raise RuntimeError(f"NVIDIA/OpenAI-compatible planner response validation failed: {exc}") from exc
