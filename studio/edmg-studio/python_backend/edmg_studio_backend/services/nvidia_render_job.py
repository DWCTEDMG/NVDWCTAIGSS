from __future__ import annotations

from typing import Any


def _float(value: Any, default: float = 0.0) -> float:
    try:
        parsed = float(value)
    except Exception:
        return default
    return parsed


def _int(value: Any, default: int) -> int:
    try:
        return int(float(value))
    except Exception:
        return default


def _path_tag(value: Any, fallback: str) -> str:
    raw = str(value or "").strip()
    cleaned = "".join(ch if ch.isalnum() or ch in {"_", "-"} else "_" for ch in raw)
    cleaned = "_".join(part for part in cleaned.split("_") if part)
    return cleaned or fallback


def build_rtx_render_job(
    scene_plan: dict[str, Any],
    *,
    project_id: str,
    project_name: str,
    fps: int = 24,
    width: int = 1920,
    height: int = 1080,
    usda_path: str = "",
) -> dict[str, Any]:
    scenes = scene_plan.get("scenes") if isinstance(scene_plan.get("scenes"), list) else []
    timeline: list[dict[str, Any]] = []
    job_tag = _path_tag(scene_plan.get("title") or project_name or project_id, "nvidia_render")
    for index, raw in enumerate(scenes, start=1):
        if not isinstance(raw, dict):
            continue
        start_s = max(0.0, _float(raw.get("start_s"), 0.0))
        end_s = max(start_s, _float(raw.get("end_s"), start_s))
        name = str(raw.get("name") or raw.get("id") or f"scene_{index}")
        output_tag = _path_tag(name, f"scene_{index}")
        timeline.append(
            {
                "id": str(raw.get("id") or f"scene_{index}"),
                "name": name,
                "start_s": start_s,
                "end_s": end_s,
                "start_frame": int(round(start_s * fps)),
                "end_frame": int(round(end_s * fps)),
                "prompt": str(raw.get("prompt") or ""),
                "camera": str(raw.get("camera") or ""),
                "look": str(raw.get("look") or ""),
                "motion": str(raw.get("motion") or ""),
                "usd_variant": str(raw.get("usd_variant") or raw.get("variant") or name),
                "output": {
                    "sequence_dir": f"outputs/nvidia/renders/{index:03d}_{output_tag}",
                    "movie": f"outputs/nvidia/renders/{index:03d}_{output_tag}.mp4",
                },
            }
        )

    duration_s = _float(scene_plan.get("duration_s"), 0.0)
    if duration_s <= 0 and timeline:
        duration_s = max(item["end_s"] for item in timeline)

    return {
        "schema_version": "edmg.nvidia.render_job.v1",
        "kind": "nvidia_rtx_render_job",
        "project": {
            "id": project_id,
            "name": project_name,
            "title": str(scene_plan.get("title") or project_name or "EDMG NVIDIA Render"),
        },
        "renderer": {
            "engine": "omniverse-kit-rtx",
            "delegate": "rtx",
            "fps": max(1, int(fps)),
            "resolution": {"width": max(1, int(width)), "height": max(1, int(height))},
            "output_format": "mp4",
        },
        "outputs": {
            "movie": f"outputs/nvidia/renders/{job_tag}.mp4",
        },
        "inputs": {
            "scene_plan_provider": str(scene_plan.get("provider") or ""),
            "usda_path": usda_path,
        },
        "timeline": timeline,
        "duration_s": duration_s,
        "scene_count": len(timeline),
        "status": "ready_for_kit_worker",
        "notes": [
            "Generated by EDMG Studio as a handoff contract for an Omniverse Kit RTX render worker.",
            "No frames are rendered until a Kit/RTX worker consumes this job.",
        ],
    }
